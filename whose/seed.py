def _insert_seed_item(conn: sqlite3.Connection, spec: dict) -> None:
    """Insert one seed item plus any claimants, and set retrieved state if specified."""
    status = spec.get("status", db.STATUS_UNCLAIMED)
    item_id = db.insert_item(
        conn,
        where_found=spec["where_found"],
        holder_type=spec["holder_type"],
        hidden_detail=spec["hidden_detail"],
        location_id=spec.get("location_id"),
        finder_contact=spec.get("finder_contact"),
        handoff_code=spec.get("handoff_code"),
        image_path=_seed_image_path(spec.get("image")),
        description=spec["description"],
        tags=spec["tags"],
        primary_type=spec.get("primary_type"),
        sensitive=spec["sensitive"],
        high_value=spec["high_value"],
        status=db.STATUS_UNCLAIMED,  # set real status after claimants exist
    )

    claimant_ids: list[int] = []
    for name, email in spec.get("claimants", []):
        claimant_ids.append(db.add_verified_claimant(conn, item_id, name, email))

    if status == db.STATUS_RETRIEVED:
        retrieved_by = spec.get("retrieved_by")
        claimant_id = (
            claimant_ids[retrieved_by]
            if retrieved_by is not None and retrieved_by < len(claimant_ids)
            else None
        )
        db.mark_retrieved(conn, item_id, claimant_id)
    elif status != db.STATUS_UNCLAIMED:
        db.set_status(conn, item_id, status)


def _json_record_to_spec(rec: dict) -> dict:
    """Convert a seed_items.json record into the spec dict _insert_seed_item expects.

    The `role` field (unclaimed | pending | retrieved) becomes a lifecycle status, and
    pending/retrieved items get a demo verified claimant so the desk and handoff views
    have data. All generated items are held at a pickup location (no AI involved here).
    """
    role = rec.get("role", "unclaimed")
    spec: dict = {
        "where_found": rec.get("where_found", "UTD campus"),
        "holder_type": db.HOLDER_LOCATION,
        "location_id": rec.get("location_id"),
        "finder_contact": None,
        "handoff_code": None,
        "image": rec.get("image"),
        "description": rec.get("description", "A found item."),
        "tags": rec.get("tags", []),
        "primary_type": rec.get("primary_type"),
        "sensitive": bool(rec.get("sensitive", False)),
        "high_value": bool(rec.get("high_value", False)),
        "hidden_detail": rec.get("hidden_detail", "A small private detail."),
    }
    if role == "pending":
        spec["status"] = db.STATUS_PENDING
        spec["claimants"] = [_PENDING_CLAIMANT]
    elif role == "retrieved":
        spec["status"] = db.STATUS_RETRIEVED
        spec["claimants"] = [_RETRIEVED_CLAIMANT]
        spec["retrieved_by"] = 0
    else:
        spec["status"] = db.STATUS_UNCLAIMED
    return spec


def _load_json_specs() -> list[dict] | None:
    """Load seed specs from seed_items.json, or None if absent/unusable.

    Returns None (so the caller uses the hardcoded fallback) when the file is missing,
    malformed, or does not contain the required demo mix (>=1 sensitive, >=1 high_value,
    >=1 pending, >=1 retrieved). Never calls the AI.
    """
    if not os.path.exists(_SEED_JSON):
        return None
    try:
        with open(_SEED_JSON, encoding="utf-8") as f:
            records = json.load(f)
    except (OSError, json.JSONDecodeError):
        return None
    if not isinstance(records, list) or not records:
        return None

    roles = {r.get("role", "unclaimed") for r in records}
    has_sensitive = any(r.get("sensitive") for r in records)
    has_high_value = any(r.get("high_value") for r in records)
    if not (has_sensitive and has_high_value and "pending" in roles and "retrieved" in roles):
        # JSON exists but lacks the required demo mix; fall back to the curated set.
        return None

    return [_json_record_to_spec(r) for r in records]


def maybe_seed(conn: sqlite3.Connection | None = None) -> int:
    """Seed demo items if the items table is empty. Returns the number inserted.

    Prefers generated data from data/seed_items.json; falls back to the curated hardcoded
    items when that file is absent or incomplete. No-op (returns 0) when the table already
    has rows. Never calls the AI.
    """
    own = conn is None
    conn = conn or db.get_conn()
    try:
        row = conn.execute("SELECT COUNT(*) AS n FROM items").fetchone()
        if row["n"] > 0:
            return 0
        specs = _load_json_specs() or _SEED_ITEMS
        for spec in specs:
            _insert_seed_item(conn, spec)
        return len(specs)
    finally:
        if own:
            conn.close()
