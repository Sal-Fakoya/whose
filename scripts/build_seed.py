@dataclass
class SeedRecord:
    """One finished seed item, serialized to seed_items.json."""

    image: str | None
    category: str
    primary_type: str
    description: str
    tags: list[str] = field(default_factory=list)
    sensitive: bool = False
    high_value: bool = False
    where_found: str = ""
    location_id: str = ""
    hidden_detail: str = ""
    role: str = "unclaimed"


@dataclass
class Credit:
    """Attribution metadata for one downloaded image."""

    image: str
    title: str
    creator: str
    source_url: str
    license: str
    license_url: str


def _search(query: str) -> list[dict]:
    """Search Openverse for photographs under CC0 / CC BY. Returns raw result dicts.

    Anonymous Openverse requests are rate limited; a burst returns HTTP 401/429. Retry a
    few times with exponential backoff so a throttle does not drop a whole category.
    """
    params = {
        "q": query,
        "license": _LICENSES,
        "category": "photograph",   # prefer real photos over illustration/vector/digitized
        "extension": "jpg,png",
        "page_size": 40,
        "mature": "false",
    }
    delay = 5
    for attempt in range(1, 6):
        resp = requests.get(_OPENVERSE, params=params, headers=_HEADERS, timeout=30)
        if resp.status_code in (401, 429):
            if attempt == 5:
                resp.raise_for_status()
            print(f"  throttled ({resp.status_code}), waiting {delay}s")
            time.sleep(delay)
            delay = min(delay * 2, 40)
            continue
        resp.raise_for_status()
        return resp.json().get("results", [])
    return []


def _title_matches(result: dict, title_any: list[str]) -> bool:
    """True if the result's title contains one of the expected category words."""
    title = (result.get("title") or "").lower()
    if not title:
        return False
    return any(word in title for word in title_any)


def _is_good_photo(img: Image.Image) -> bool:
    """Reject tiny, extreme-aspect, or near-grayscale images."""
    w, h = img.size
    if min(w, h) < _MIN_EDGE:
        return False
    if max(w, h) / min(w, h) > _MAX_ASPECT:
        return False
    rgb = img.convert("RGB")
    r, g, b = ImageStat.Stat(rgb).mean
    if max(r, g, b) - min(r, g, b) < 4:  # near-grayscale -> likely a diagram/scan
        return False
    return True


def _download_image(url: str) -> Image.Image | None:
    """Download and decode an image, or None on failure."""
    try:
        resp = requests.get(url, headers=_HEADERS, timeout=30)
        resp.raise_for_status()
        img = Image.open(io.BytesIO(resp.content))
        img.load()
        return img
    except Exception as exc:  # noqa: BLE001
        print(f"    skip (download/decode failed): {exc}")
        return None


def _save_resized(img: Image.Image, dest_path: str) -> None:
    out = img.convert("RGB")
    out.thumbnail((_MAX_EDGE, _MAX_EDGE))
    out.save(dest_path, format="JPEG", quality=85)


def _collect_category(cat: dict, credits: list[Credit]) -> list[SeedRecord]:
    """Find, filter, download, and build up to _PER_CATEGORY records for one category."""
    print(f"== {cat['key']} ==")
    try:
        results = _search(cat["query"])
    except Exception as exc:  # noqa: BLE001
        print(f"  ! search failed: {exc}")
        return []

    records: list[SeedRecord] = []
    for r in results:
        if len(records) >= _PER_CATEGORY:
            break
        if not r.get("url") or not _title_matches(r, cat["title_any"]):
            continue
        img = _download_image(r["url"])
        if img is None:
            continue
        if not _is_good_photo(img):
            print(f"    skip (quality): {(r.get('title') or '')[:50]}")
            continue

        filename = f"{cat['key']}_{len(records) + 1}.jpg"
        _save_resized(img, os.path.join(_SEED_IMG_DIR, filename))
        print(f"    saved {filename} ({(r.get('title') or '')[:50]})")

        credits.append(
            Credit(
                image=filename,
                title=r.get("title", ""),
                creator=r.get("creator", ""),
                source_url=r.get("foreign_landing_url") or r.get("url", ""),
                license=f"{str(r.get('license', '')).upper()} "
                f"{r.get('license_version', '')}".strip(),
                license_url=r.get("license_url", "") or "https://creativecommons.org/",
            )
        )
        records.append(
            SeedRecord(
                image=filename,
                category=cat["key"],
                primary_type=cat["primary_type"],
                description=cat["description"],
                tags=cat["tags"],
                sensitive=False,
                high_value=bool(cat.get("high_value", False)),
                where_found=cat["where_found"],
                location_id=cat["location_id"],
                hidden_detail=cat["hidden_detail"],
            )
        )
    if not records:
        print("  ! no suitable photo found for this category")
    return records


def _enforce_required_mix(records: list[SeedRecord]) -> None:
    """Guarantee >=1 sensitive, >=1 high_value, >=1 pending, >=1 retrieved."""
    if not records:
        return
    if not any(r.high_value for r in records):
        for r in records:
            if r.primary_type in ("laptop", "headphones"):
                r.high_value = True
                break
    # Assign pending + retrieved to two non-sensitive photo items for desk/handoff demos.
    non_sensitive = [r for r in records if not r.sensitive and r.image]
    if non_sensitive and not any(r.role == "pending" for r in records):
        non_sensitive[0].role = "pending"
    later = [r for r in non_sensitive if r.role == "unclaimed"]
    if later and not any(r.role == "retrieved" for r in records):
        later[0].role = "retrieved"


def _write_json(records: list[SeedRecord]) -> None:
    with open(_SEED_JSON, "w", encoding="utf-8") as f:
        json.dump([asdict(r) for r in records], f, indent=2, ensure_ascii=False)


def _write_credits(credits: list[Credit]) -> None:
    lines = [
        "# Seed image credits",
        "",
        "Demo images were sourced from Openverse (https://openverse.org), filtered to "
        "CC0 1.0 and CC BY 4.0 licenses and to photographs only. CC0 images are public "
        "domain; CC BY images are reused here with attribution as required by their license. "
        "Images were resized to a maximum of 800px for this demo.",
        "",
        "| Image | Title | Creator | Source | License |",
        "| --- | --- | --- | --- | --- |",
    ]
    for c in credits:
        lines.append(
            f"| `{c.image}` | {c.title or '-'} | {c.creator or '-'} | "
            f"[source]({c.source_url}) | [{c.license}]({c.license_url}) |"
        )
    lines.append("")
    with open(_CREDITS, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def main() -> None:
    os.makedirs(_SEED_IMG_DIR, exist_ok=True)
    credits: list[Credit] = []
    records: list[SeedRecord] = []

    for idx, cat in enumerate(_CATEGORIES):
        if idx > 0:
            time.sleep(3)  # space out searches to stay under the anonymous rate limit
        records.extend(_collect_category(cat, credits))

    # Add photoless sensitive items as SeedRecords.
    for item in _PHOTOLESS_ITEMS:
        records.append(
            SeedRecord(
                image=item["image"],
                category=item["category"],
                primary_type=item["primary_type"],
                description=item["description"],
                tags=item["tags"],
                sensitive=item["sensitive"],
                high_value=item["high_value"],
                where_found=item["where_found"],
                location_id=item["location_id"],
                hidden_detail=item["hidden_detail"],
                role=item["role"],
            )
        )

    _enforce_required_mix(records)
    _write_json(records)
    _write_credits(credits)

    # Validate location ids against config.
    valid = {loc["id"] for loc in config.PICKUP_LOCATIONS}
    bad = [r.image or r.category for r in records if r.location_id not in valid]

    print(
        f"\nDone. {len(records)} items -> {_SEED_JSON}\n"
        f"  with photos: {sum(1 for r in records if r.image)}\n"
        f"  sensitive: {sum(r.sensitive for r in records)}"
        f" | high_value: {sum(r.high_value for r in records)}"
        f" | pending: {sum(r.role == 'pending' for r in records)}"
        f" | retrieved: {sum(r.role == 'retrieved' for r in records)}"
    )
    if bad:
        print("  ! WARNING: unknown location ids on:", bad)


if __name__ == "__main__":
    main()
