"""One-time script to build demo seed data for Whose? from openly-licensed PHOTOS.

Source: Openverse (https://openverse.org), filtered to CC0 1.0 and CC BY 4.0 licenses
(reuse allowed, with attribution). We request photographs only and apply precision and
quality filters so the saved images are natural single-item photos, not illustrations,
vectors, banners, or off-topic shots.

Pipeline:
  1. Search Openverse per category, photographs only, CC0 / CC BY only.
  2. Keep only results whose title clearly names the category, then download and apply
     quality filters (min size, roughly square-ish aspect, not near-grayscale).
  3. Resize each kept image so its longest side is <= 800px and save to data/seed_images/.
  4. Write data/seed_items.json with curated, photo-accurate descriptions and synonym-rich
     tags (10-15 each), a primary_type for ranking, realistic UTD locations, invented
     hidden details, and the required demo mix (>=1 sensitive, high_value, pending,
     retrieved). Sensitive items are added WITHOUT photos (their photos are hidden anyway).
  5. Write data/seed_images/CREDITS.md with per-image attribution and license.

Descriptions and tags are CURATED here (not generated by a model), so the script is fast,
deterministic, and never depends on an AI call. The app itself never downloads anything and
never calls the AI at startup.

Run from the project root:  python scripts/build_seed.py
Requires `requests` and `pillow` (dev-only; not in requirements.txt). No emojis.
"""

